export const getBookingById = (bookingId) => {
  if (!bookingId) return MOCK_BOOKINGS[0];
  const found = MOCK_BOOKINGS.find(
    (b) => b.id.toLowerCase() === bookingId.toLowerCase()
  );
  return found || MOCK_BOOKINGS[0];
};

export const getTicketById = (ticketId) => {
  for (const booking of MOCK_BOOKINGS) {
    if (booking.individualTickets) {
      const t = booking.individualTickets.find(
        (item) => item.id.toLowerCase() === ticketId?.toLowerCase()
      );
      if (t) return { booking, ticket: t };
    }
  }
  return {
    booking: MOCK_BOOKINGS[0],
    ticket: MOCK_BOOKINGS[0].individualTickets[0],
  };
};
